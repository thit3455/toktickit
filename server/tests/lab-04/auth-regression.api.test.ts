import { beforeAll, afterAll, describe, it, expect, vi } from "vitest";
import type { PrismaClient } from "@prisma/client";
import bcrypt from "bcrypt";
import request from "supertest";
import { app } from "../../src/app.js";
import { isolatedLab4Database } from "../helpers/lab4-database.js";
import { assertI6DatabaseConfiguration } from "../helpers/i6-database.js";
let db: PrismaClient;
vi.mock("../../src/prisma.js", () => ({ getPrisma: () => db }));
describe.skipIf(process.env.LAB4_I6_TEST_APPROVED !== "1")("Initial-password regression for every role", () => {
    let owned: Awaited<ReturnType<typeof isolatedLab4Database>>;
    beforeAll(async () => { assertI6DatabaseConfiguration(); owned = await isolatedLab4Database(); db = owned.prisma; owned.migrate(); }, 120000);
    afterAll(async () => { await owned?.dispose(); });
    it.each(["REQUESTER", "IT_STAFF", "ADMINISTRATOR"] as const)("requires %s to choose a different password, then permits normal access without another mandatory prompt", async (role) => {
        const initial = "InitialI6Password123!", changed = "ChangedI6Password123!", email = "i6-gate-" + role + "@example.test";
        const user = await db.user.create({ data: { name: "I6 first-login " + role, email, role, passwordHash: await bcrypt.hash(initial, 4), mustChangePassword: true } });
        const agent = request.agent(app), endpoint = role === "REQUESTER" ? "/api/requester/dashboard" : "/api/staff/dashboard";
        expect((await agent.post("/api/auth/login").send({ email, password: initial })).status).toBe(200);
        const gate = await agent.get(endpoint);
        expect(gate.status).toBe(403);
        expect(gate.body.error.code).toBe("PASSWORD_CHANGE_REQUIRED");
        const reused = await agent.post("/api/auth/change-password").send({ currentPassword: initial, newPassword: initial });
        expect(reused.status).toBe(400);
        expect(reused.body.error.code).toBe("WEAK_PASSWORD");
        const untouched = await db.user.findUniqueOrThrow({ where: { id: user.id } });
        expect(untouched.mustChangePassword).toBe(true);
        expect(untouched.passwordHash === user.passwordHash).toBe(true);
        expect(untouched.role).toBe(role);
        expect((await agent.post("/api/auth/change-password").send({ currentPassword: initial, newPassword: changed })).status).toBe(200);
        expect((await agent.get("/api/auth/me")).body.data.mustChangePassword).toBe(false);
        expect((await agent.get(endpoint)).status).toBe(200);
        expect((await agent.post("/api/auth/logout")).status).toBe(200);
        expect((await agent.get(endpoint)).status).toBe(401);
        expect((await agent.post("/api/auth/login").send({ email, password: initial })).status).toBe(401);
        const subsequent = await agent.post("/api/auth/login").send({ email, password: changed });
        expect(subsequent.status).toBe(200);
        expect(subsequent.body.data.user.mustChangePassword).toBe(false);
        expect((await agent.get(endpoint)).status).toBe(200);
        const session = await db.session.findFirstOrThrow({ where: { userId: user.id } });
        await db.session.update({ where: { id: session.id }, data: { expiresAt: new Date(Date.now() - 1000) } });
        const expired = await agent.get(endpoint);
        expect(expired.status).toBe(401);
        expect(expired.body.error.code).toBe("SESSION_EXPIRED");
    }, 30000);
});
